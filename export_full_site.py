"""Writes site/js/full_data.js: the full-machine results, the Real programs cards, the CPI cards
and the real-transaction judge examples, all from files in results/."""
import json, os

R = 'results/'
load = lambda f, d=None: json.load(open(R + f)) if os.path.exists(R + f) else d
summary = json.load(open(R + 'full_summary.json'))
data = {
    'summary': summary,
    'showcase': load('showcase.json', []),
    'cpi': load('showcase_cpi.json', []),
    'judge_real': load('judge_real.json', []),
}
with open('site/js/full_data.js', 'w') as f:
    f.write('// Generated by export_full_site.py from results/.\nwindow.SVM_FULL = ' + json.dumps(data) + ';\n')
print('wrote site/js/full_data.js', os.path.getsize('site/js/full_data.js'), 'bytes')

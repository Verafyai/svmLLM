"""Writes the site's data file (demos, real weights traces, test results, judge examples, code excerpts)
and a parity fixture used by tests/js_parity.mjs to check the browser interpreter against svllm/ref.py."""
import json, os, random, re, sys
from svllm.programs import DEMOS, preset_mem, conformance_cases, demo_cases
from svllm.randprog import gen
from svllm import ref
from svllm.isa import assemble

SITE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'site')
res = json.load(open('results/results.json'))
traces = json.load(open('results/weights_traces.json'))
judge = json.load(open('results/judge_examples.json'))
src = open('svllm/machine.py').read()


def excerpt(start, end):
    a = src.index(start); b = src.index(end, a)
    return src[a:b].rstrip()


demos = []
for d in DEMOS:
    demos.append({'id': d['id'], 'title': d['title'], 'blurb': d['blurb'], 'asm': d['asm'],
                  'size': len(assemble(d['asm'])) // 8,
                  'presets': [{'label': l, 'mem': preset_mem(p).hex(), 'spec': p if isinstance(p, str) else ', '.join(str(x) for x in p), 'weights': traces.get(f"demo/{d['id']}/{l}")} for l, p in d['presets']]})
code = {
    'lut': excerpt('class LUT:', '\nclass DeltaNetRAM'),
    'deltanet': excerpt('class DeltaNetRAM:', '\ndef AND'),
    'tables': excerpt('L_ADD = ', '\nL_OR'),
    'adder': excerpt('def add(A, B, cin):', '\ndef sub'),
    'fetch': excerpt('        # fetch:', '        # register reads'),
    'regs': excerpt('        # register reads', '        # ---------------- ALU'),
    'alu': excerpt('        branches = {', '        div0 ='),
    'write': excerpt('        # ---------------- writes', '        self.pc = mux'),
    'driver': excerpt('def run(prog', '    mem = bytes'),
}
data = {'demos': demos, 'results': {k: v for k, v in res.items() if k != 'failures'}, 'failures': len(res.get('failures', [])),
        'judge': judge, 'code': code}
os.makedirs(SITE + '/js', exist_ok=True)
with open(SITE + '/js/data.js', 'w') as f:
    f.write('// Generated by export_site.py from real runs. Weights traces come from svllm/machine.py.\n')
    f.write('window.SVM_DATA = ' + json.dumps(data) + ';\n')
# parity fixture
rng = random.Random(7)
cases = conformance_cases() + demo_cases() + [(f'random/{i}', *gen(rng), 200) for i in range(400)]
fx = []
for n, p, m, lim in cases:
    r = ref.run(p, m, lim)
    fx.append({'name': n, 'prog': p.hex(), 'mem': m.hex(), 'lim': lim, 'status': r['status'], 'r0': str(r['r0']), 'cu': r['cu'], 'out': r['mem'].hex()})
asm = [{'id': d['id'], 'asm': d['asm'], 'hex': assemble(d['asm']).hex()} for d in DEMOS]
os.makedirs('tests', exist_ok=True)
json.dump({'cases': fx, 'asm': asm, 'judge': judge}, open('tests/parity_fixture.json', 'w'))
print('wrote', SITE + '/js/data.js', 'and tests/parity_fixture.json', len(fx), 'cases')
